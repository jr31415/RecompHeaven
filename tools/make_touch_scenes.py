#!/usr/bin/env python3
"""Emit the [[scene]] / [[touch_button]] sections of game.toml from the ROM + game-overlays.json.

  make_touch_scenes.py IMAGES GAME_OVERLAYS.json  >> game.toml

Scene fingerprints are FNV-1a 64 hashes of the first 512 bytes of each resident overlay
(hashes only; no ROM bytes are written). `minigame` = any game overlay in slot 0x0228FA60
(the menu's overlay is excluded); `guitar` = overlay 33 in slot 0x02287660 (Guitar Lessons,
Rockers, Rockers 2 all run on it).
"""
import json, sys
from pathlib import Path

LEN = 512
def fnv(b):
    h = 1469598103934665603
    for x in b: h = ((h ^ x) * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return f"{h:016x}"

img = Path(sys.argv[1]); ov = {r["id"]: r for r in json.load(open(img / "overlays.json"))}
d = json.load(open(sys.argv[2]))
def h(i): return fnv((img / "overlays" / ov[i]["file"]).read_bytes()[:LEN])
menu3 = {v["menu"]["0x0228FA60"] for v in d.values()}
game3 = sorted({v["slots"]["0x0228FA60"] for v in d.values()} - menu3 - {None})
guitar2 = [33]
fmt = lambda hs: "[" + ", ".join(f'"{x}"' for x in hs) + "]"
print(f"""
# Touch buttons painted into the touch screen (generated by tools/make_touch_scenes.py).
[[scene]]
name = "minigame"
addr = 0x0228FA60
len = {LEN}
hashes = {fmt([h(i) for i in game3])}

[[scene]]
name = "guitar"
addr = 0x02287660
len = {LEN}
hashes = {fmt([h(i) for i in guitar2])}

[[touch_button]]
name = "pause"
icon = "pause"
corner = "top-right"
width = 20
height = 20
keys = ["select"]
scenes = ["minigame"]

[[touch_button]]
name = "bend"
icon = "bend"
corner = "bottom-right"
width = 34
height = 20
keys = ["l", "r"]
scenes = ["guitar"]
""")
